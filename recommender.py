import joblib

MODEL_PATH = "recommender_itemcf_v1.joblib"


def load_model(path=MODEL_PATH):
    return joblib.load(path)


def get_history(model, customer_id):
    """สินค้าที่ลูกค้าเคยซื้อ (ว่างเปล่าถ้าเป็นลูกค้าใหม่)"""
    u = model["user_index"].get(customer_id)
    if u is None:
        return []
    items = model["item_ids"][model["X"][u].indices]
    return [
        {"product_id": i, "category": model["item_category"].get(i, "unknown")}
        for i in items
    ]


def recommend(model, customer_id, k=10):
    item_ids = model["item_ids"]
    u = model["user_index"].get(customer_id)

    recs = []
    seen = set()

    # 1) ลูกค้าเก่า: หาสินค้าที่คล้ายกับของที่เคยซื้อ
    if u is not None:
        user_row = model["X"][u]
        seen = set(item_ids[user_row.indices])

        scores = (user_row @ model["item_sim"]).toarray().ravel()
        scores[user_row.indices] = 0

        candidates = scores.nonzero()[0]
        candidates = candidates[scores[candidates] > 0]
        order = candidates[(-scores[candidates]).argsort(kind="mergesort")][:k]

        recs = [
            (item_ids[i], "similar_items", round(float(scores[i]), 4))
            for i in order
        ]

    # 2) เติมด้วยสินค้าขายดีล่าสุดจนครบ k ชิ้น
    chosen = {item for item, _, _ in recs}
    for item in model["pop_ranking"]:
        if len(recs) >= k:
            break
        if item not in seen and item not in chosen:
            recs.append((item, "popular_recent", None))
            chosen.add(item)

    return [
        {
            "rank": rank,
            "product_id": item,
            "category": model["item_category"].get(item, "unknown"),
            "source": source,
            "score": score,
        }
        for rank, (item, source, score) in enumerate(recs, start=1)
    ]